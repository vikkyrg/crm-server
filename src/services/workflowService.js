import Workflow from '../models/Workflow.js';
import Task from '../models/Task.js';
import Notification from '../models/Notification.js';

export const triggerWorkflow = async (triggerEvent, payload = {}) => {
  try {
    const workflows = await Workflow.find({ trigger: triggerEvent, isActive: true });
    for (const wf of workflows) {
      console.log(`⚡ Executing Workflow: [${wf.name}] for trigger: ${triggerEvent}`);

      for (const actionItem of wf.actions || []) {
        if (actionItem.type === 'CreateTask' && payload.userId) {
          await Task.create({
            taskName: actionItem.title || `Workflow Task: ${wf.name}`,
            description: actionItem.description || `Auto generated by workflow ${wf.name}`,
            assignedEmployee: payload.userId,
            project: payload.projectId || null,
            priority: 'High',
            status: 'To Do',
            createdBy: payload.createdBy || payload.userId
          });
        }
        if (actionItem.type === 'SendNotification' && payload.userId) {
          await Notification.create({
            user: payload.userId,
            title: actionItem.title || `Workflow Notification`,
            message: actionItem.message || `Automated alert for ${triggerEvent}`,
            type: 'Workflow'
          });
        }
      }
    }
  } catch (err) {
    console.error('Workflow Execution Error:', err.message);
  }
};
